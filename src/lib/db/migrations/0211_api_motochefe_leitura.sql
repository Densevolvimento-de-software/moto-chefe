-- #317 (API de leitura MotoChefe, #315): estrutura que a API precisa, antes do código que a usa.
-- Sem GRANT nem policy: o app lê e grava pelo Drizzle, e a 0187 confere que anon e authenticated ficam sem acesso.

-- Loja MotoChefe: desligada por padrão; só o admin_geral liga (tela do #321).
alter table lojas add column loja_motochefe boolean not null default false;

-- Conta autorizada a sair com custo de compra, despesa e meta: desligada por padrão; só o admin_geral liga (#321).
alter table contas add column autoriza_custo_despesa_meta boolean not null default false;

-- Chave de acesso: só o hash (sha256 de uma chave aleatória de 256 bits). A chave aparece uma vez, na geração.
create table api_chaves (
  id          uuid primary key default gen_random_uuid(),
  hash        text not null unique,
  -- Sem FK: quem gerou fica como histórico (a 0136 fez o mesmo no log_acoes), e excluir o usuário não pode falhar.
  gerada_por  uuid not null,
  gerada_em   timestamptz not null default now(),
  valida_ate  timestamptz,
  revogada_em timestamptz
);
-- Índice sobre expressão constante dentro do WHERE: no máximo uma linha com valida_ate e revogada_em nulos (a chave atual).
create unique index api_chaves_atual_key on api_chaves ((revogada_em is null))
  where valida_ate is null and revogada_em is null;

-- Registro de cada chamada da API, inclusive a recusada (chave_id nulo quando não havia chave).
-- Não usa log_acoes: ele exige usuario_id, e a chamada vem de uma chave, não de um usuário.
create table api_acessos (
  id          bigint generated by default as identity primary key,
  chave_id    uuid references api_chaves(id),
  endpoint    text not null,
  periodo_ini date,
  periodo_fim date,
  pagina      integer,
  ip          text,
  user_agent  text,
  linhas      integer,
  status      integer not null,
  criado_em   timestamptz not null default now()
);
create index api_acessos_criado_em_idx on api_acessos (criado_em);

-- Contador do limite de chamadas por chave: uma linha por chave e minuto.
create table api_limite (
  chave_id uuid not null references api_chaves(id),
  janela   timestamptz not null,
  pedidos  integer not null default 0,
  primary key (chave_id, janela)
);

-- RLS sem policy fecha as três tabelas para o PostgREST; o app lê e grava pelo Drizzle.
alter table api_chaves enable row level security;
alter table api_acessos enable row level security;
alter table api_limite enable row level security;
